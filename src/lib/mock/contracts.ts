import { riskLevelFromScore, type Contract } from "@/lib/schemas";

type Input = Omit<Contract, "riskLevel" | "mitigated"> & { riskLevel?: Contract["riskLevel"] };

function contract(input: Input): Contract {
  return {
    ...input,
    mitigated: input.originalExposure - input.currentExposure,
    riskLevel: input.riskLevel ?? riskLevelFromScore(input.likelihood * input.impact),
  };
}

